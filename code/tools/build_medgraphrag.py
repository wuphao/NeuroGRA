"""Build reusable MedGraphRAG knowledge graphs directly from a PDF folder."""
import argparse
from datetime import datetime
from pathlib import Path
import sys
import uuid

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'code'))
import yaml
from neurogra.benchmarks.medgraphrag.folder_build import build_folder
from neurogra.benchmarks.medgraphrag.runtime import Config


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pdf-folder', type=Path, required=True)
    parser.add_argument('--dictionary-folder', type=Path, help='Optional real dictionary PDFs, bottom layer')
    parser.add_argument('--config', type=Path, default=ROOT / 'configs/medgraphrag.baseline.yaml')
    parser.add_argument('--output', type=Path, help='New output directory; autogenerated when omitted')
    parser.add_argument('--no-recursive', action='store_true')
    parser.add_argument('--check', action='store_true', help='Parse PDFs and report issues without model/database calls')
    parser.add_argument('--resume', action='store_true', help='Reuse valid cached documents in an existing output directory')
    args = parser.parse_args(argv)
    config_path = args.config.resolve()
    config = Config.model_validate(yaml.safe_load(config_path.read_text(encoding='utf-8-sig')) or {})
    if config.knowledge_cache and not Path(config.knowledge_cache).is_absolute():
        config.knowledge_cache = str((config_path.parent / config.knowledge_cache).resolve())
    if config.model_cache and not Path(config.model_cache).is_absolute():
        config.model_cache = str((config_path.parent / config.model_cache).resolve())
    if args.resume and args.output is None:
        parser.error('--resume requires --output')
    output = args.output or ROOT / 'output/baselines/medgraphrag/knowledge_build' / (
        datetime.now().strftime('%Y%m%d-%H%M%S') + '-' + uuid.uuid4().hex[:8])
    def progress(summary):
        counts = summary['counts']
        print(f'[{summary["status"]}] parsed={counts["parsed"]} built={counts["built"]} '
              f'duplicate={counts["duplicate"]} failed={counts["failed"]}', flush=True)
    summary = build_folder(args.pdf_folder, config, output, recursive=not args.no_recursive,
                           dictionary_folder=args.dictionary_folder, check=args.check, resume=args.resume,
                           progress=progress)
    print(f'{summary["status"]}: {summary["counts"]}; output={output.resolve()}')
    if summary.get('error'):
        print(summary['error']['message'], file=sys.stderr)
    return 0 if summary['status'] in {'completed', 'checked'} else 2 if summary['status'] == 'partial' else 1


if __name__ == '__main__':
    raise SystemExit(main())
